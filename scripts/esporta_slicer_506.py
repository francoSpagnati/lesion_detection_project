#!/usr/bin/env python
"""Esporta le segmentazioni di Dataset506 in file pronti per 3D Slicer.

    python scripts/esporta_slicer_506.py           # i 5 pazienti di test  -> esportazioni/506_test/
    python scripts/esporta_slicer_506.py --cv      # i 12 di addestramento, predizioni fuori-fold -> esportazioni/506_cv/

PERCHE'. Le figure mostrano poche fette scelte da noi; per capire dove il modello sbaglia serve
scorrere tutto il volume e girare attorno alla lesione in 3D. 3D Slicer e' lo strumento indicato
dall'utente per questo, perche' rende le segmentazioni come superfici e non solo come fette.

CHE COSA SCRIVE, per paziente, tutto nella griglia T1 nativa (dove si misura):
  T1.nii.gz, FLAIR.nii.gz          le due sequenze, corrette N4, in interi a 16 bit; la FLAIR portata
                                   sulla T1 con la rigida della pipeline
  confronto_<Z|A|D>.seg.nrrd       segmentazione di Slicer con tre segmenti che non si sovrappongono:
                                   1 lesione trovata (annotata e predetta), 2 mancata (solo
                                   annotazione), 3 falso positivo (solo predizione). Si apre
                                   trascinandola in Slicer, con nomi e colori gia' impostati
  cervello.seg.nrrd                maschera del cervello (SynthStrip), per orientarsi in 3D
  annotazione.nii.gz, predizione_<k>.nii.gz, probabilita_<k>.nii.gz
                                   le stesse cose come NIfTI semplici, per qualunque altro programma
Nella cartella principale: apri_in_slicer.py (carica un paziente e imposta le viste) e LEGGIMI.txt.

Le predizioni sono quelle gia' valutate: probabilita' nel nativo (cache prob_nativa) e postprocessing
congelato di ciascuna ricetta. Il controllo finale rilegge ogni .seg.nrrd con SimpleITK e verifica
geometria e contenuto contro il NIfTI della T1: un file di Slicer scritto a mano non deve poter
finire spostato di un voxel senza che ce ne accorgiamo.

I file contengono immagini di pazienti: la cartella `esportazioni/` e' esclusa da git.
"""
import gzip
import json
import shutil
import sys
from pathlib import Path

import ants
import nibabel as nib
import numpy as np
import SimpleITK as sitk

sys.path.insert(0, str(Path(__file__).resolve().parent))
import postprocessing_aincp as pp  # noqa: E402

PROGETTO = Path(__file__).resolve().parent.parent
R = PROGETTO / 'nnUNet/nnUNet_results/Dataset506_AINCP_FINALE'
RICETTE = {'Z': 'nnUNetTrainerWandb_250ep_dropmod30_arresto50',
           'A': 'nnUNetTrainerEspansioneCanali_zero_250ep_lr1e4_primo1e2_wdfix_dropmod30_arresto50',
           'D': 'nnUNetTrainerEspansioneCanali_zero_250ep_lr1e4_dropmod30_arresto50_dapre2c'}
# stessi colori delle figure: blu = annotazione, arancio = predizione; acqua = entrambe
SEGMENTI = [(1, 'lesione trovata', '#1baf7a'), (2, 'lesione mancata', '#2a78d6'), (3, 'falso positivo', '#eb6834')]


def rgb(h):
    return ' '.join(f'{int(h[i:i + 2], 16) / 255:.4f}' for i in (1, 3, 5))


def scrivi_seg_nrrd(f: Path, lab: np.ndarray, aff: np.ndarray, segmenti):
    """Segmentazione di Slicer a un solo strato (segmenti disgiunti), formato .seg.nrrd.

    NRRD vuole lo spazio LPS, il NIfTI e' RAS: si cambia segno alle prime due righe dell'affine.
    L'asse piu' veloce del NRRD e' il primo (x), quindi i dati si scrivono in ordine Fortran."""
    lps = np.diag([-1, -1, 1]) @ aff[:3, :]
    dirs = ' '.join('(' + ','.join(f'{v:.10g}' for v in lps[:, j]) + ')' for j in range(3))
    orig = '(' + ','.join(f'{v:.10g}' for v in lps[:, 3]) + ')'
    X, Y, Z = lab.shape
    h = ['NRRD0004', 'type: unsigned char', 'dimension: 3', 'space: left-posterior-superior',
         f'sizes: {X} {Y} {Z}', f'space directions: {dirs}', 'kinds: domain domain domain',
         'encoding: gzip', f'space origin: {orig}']
    for i, (val, nome, col) in enumerate(segmenti):
        h += [f'Segment{i}_Color:={rgb(col)}', f'Segment{i}_ColorAutoGenerated:=0',
              f'Segment{i}_Extent:=0 {X - 1} 0 {Y - 1} 0 {Z - 1}', f'Segment{i}_ID:=Segment_{val}',
              f'Segment{i}_LabelValue:={val}', f'Segment{i}_Layer:=0', f'Segment{i}_Name:={nome}',
              f'Segment{i}_NameAutoGenerated:=0', f'Segment{i}_Tags:=|']
    h += ['Segmentation_ContainedRepresentationNames:=Binary labelmap|',
          'Segmentation_MasterRepresentation:=Binary labelmap',
          'Segmentation_ReferenceImageExtentOffset:=0 0 0']
    with open(f, 'wb') as o:
        o.write(('\n'.join(h) + '\n\n').encode())
        o.write(gzip.compress(np.ascontiguousarray(lab.astype(np.uint8).ravel(order='F')).tobytes()))


def controlla(seg: Path, t1: Path, lab: np.ndarray):
    a, b = sitk.ReadImage(str(seg)), sitk.ReadImage(str(t1))
    assert np.allclose(a.GetOrigin(), b.GetOrigin(), atol=1e-3), (seg, a.GetOrigin(), b.GetOrigin())
    assert np.allclose(a.GetSpacing(), b.GetSpacing(), atol=1e-4), seg
    assert np.allclose(a.GetDirection(), b.GetDirection(), atol=1e-4), seg
    # SimpleITK restituisce (z, y, x)
    assert np.array_equal(sitk.GetArrayFromImage(a).transpose(2, 1, 0), lab), seg


def esporta(caso: str, dest: Path, insieme: str):
    s = pp.sessione(caso)
    dest.mkdir(parents=True, exist_ok=True)
    t1n = nib.load(str(s / 'T1_N4.nii.gz'))
    aff = t1n.affine
    t1a = ants.image_read(str(s / 'T1_N4.nii.gz'))
    fl = ants.apply_transforms(fixed=t1a, moving=ants.image_read(str(s / 'FLAIR_N4.nii.gz')),
                               transformlist=[str(s / 'transforms' / 'FLAIR_to_T1_0.mat')], interpolator='linear')
    ref, cer, vox = pp.carica_caso(caso)

    def salva(nome, arr, dtype, pendenza=None):
        img = nib.Nifti1Image(arr.astype(dtype), aff)
        img.set_qform(aff, code=1); img.set_sform(aff, code=1)
        if pendenza is not None:
            img.header.set_slope_inter(pendenza, 0)
        nib.save(img, str(dest / nome))

    # le immagini N4 sono float32 e pesano oltre 100 MB l'una (il rumore in virgola mobile non si
    # comprime): per guardarle bastano interi a 16 bit, riscalati sul 99.9 percentile del cervello
    for nome, im in (('T1.nii.gz', t1a.numpy()), ('FLAIR.nii.gz', fl.numpy())):
        alto = float(np.percentile(im[cer], 99.9))
        salva(nome, np.clip(np.rint(im / alto * 1000), 0, 32767), np.int16)

    salva('annotazione.nii.gz', ref, np.uint8)
    scrivi_seg_nrrd(dest / 'cervello.seg.nrrd', cer.astype(np.uint8), aff, [(1, 'cervello', '#c9c8c3')])
    controlla(dest / 'cervello.seg.nrrd', dest / 'T1.nii.gz', cer.astype(np.uint8))
    riepilogo = {}
    for k, tr in RICETTE.items():
        run = R / f'{tr}__nnUNetPlansDa502__3d_fullres'
        par = json.loads((PROGETTO / 'reports' / f'postprocessing_{R.name}__{run.name}.json').read_text())['scelto']
        cache = run / 'prob_nativa' if insieme == 'cv' else run / 'test_insieme' / 'prob_nativa'
        prob = np.load(cache / f'{caso}.npy').astype(np.float32)
        pred = pp.postprocessa(prob, par['t'], par['vmin'], par['cervello'], cer, vox)
        # in 8 bit con pendenza 1/255 nell'intestazione: Slicer e nibabel rileggono valori fra 0 e 1
        salva(f'probabilita_{k}.nii.gz', np.rint(np.clip(prob, 0, 1) * 255), np.uint8, 1 / 255)
        salva(f'predizione_{k}.nii.gz', pred, np.uint8)
        lab = np.zeros(ref.shape, np.uint8)
        lab[ref & pred], lab[ref & ~pred], lab[~ref & pred] = 1, 2, 3
        scrivi_seg_nrrd(dest / f'confronto_{k}.seg.nrrd', lab, aff, SEGMENTI)
        controlla(dest / f'confronto_{k}.seg.nrrd', dest / 'T1.nii.gz', lab)
        m = pp.misure(pred, ref, cer, vox)
        riepilogo[k] = {'dice': round(m['dice'], 3), 'ml_vero': round(m['ml_vero'], 2), 'ml_predetto': round(m['ml_pred'], 2),
                        'lesioni_rilevate': f"{sum(l['rilevata'] for l in m['lesioni'])}/{len(m['lesioni'])}",
                        'falsi_positivi': m['fp'], 'soglia': par['t'], 'volume_minimo_mm3': par['vmin']}
    (dest / 'riepilogo.json').write_text(json.dumps(riepilogo, indent=1))
    return riepilogo


def main():
    insieme = 'cv' if '--cv' in sys.argv else 'test'
    radice = PROGETTO / 'esportazioni' / f'506_{insieme}'
    run_z = R / f"{RICETTE['Z']}__nnUNetPlansDa502__3d_fullres"
    cache = run_z / 'prob_nativa' if insieme == 'cv' else run_z / 'test_insieme' / 'prob_nativa'
    casi = sorted(f.stem for f in cache.glob('*.npy'))
    for c in casi:
        r = esporta(c, radice / c, insieme)
        print(c, ' | '.join(f"{k}: Dice {v['dice']}, {v['lesioni_rilevate']}, FP {v['falsi_positivi']}" for k, v in r.items()),
              flush=True)
    shutil.copyfile(Path(__file__).resolve().parent / 'apri_in_slicer.py', radice / 'apri_in_slicer.py')
    shutil.copyfile(Path(__file__).resolve().parent / 'LEGGIMI_slicer.txt', radice / 'LEGGIMI.txt')
    print('scritto', radice)


if __name__ == '__main__':
    main()
